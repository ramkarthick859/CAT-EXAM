  col_check, col_day, col_topic, col_action, col_link = st.columns([0.6, 1.2, 2.2, 3.5, 1.5])

  with col_check:
    checked = st.checkbox(
        "", value=is_checked, key=f"chk_{task_id}", label_visibility="collapsed"
    )
    if checked:
      st.session_state["completed_tasks"].add(task_id)
    else:
      st.session_state["completed_tasks"].discard(task_id)

  with col_day:
    st.write(f"**{row['Day']}**\n\n`{row['Date']}`")

  with col_topic:
    st.write(f"**{row['Section & Topic']}**")
    st.caption(row["What to Study / Search"])

  with col_action:
    st.write(row["60-Minute Action Item"])

  with col_link:
    if row["Link"]:
      st.markdown(f"[🔗 Open Resource]({row['Link']})")
    else:
      st.write("-")

  st.divider()